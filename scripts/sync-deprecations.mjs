#!/usr/bin/env node
/*
 * sync-deprecations — vendor the deprecations of abap2UI5, as the documentation
 * publishes them.
 *
 * What was deprecated, removed or moved out of abap2UI5 is decided and written
 * down in ONE place: the table on resources/deprecations.md of abap2UI5/docs.
 * That repository generates docs/public/api/deprecations.json from it (its
 * `check:deprecations` holds the two together) and publishes the file at
 * https://abap2ui5.github.io/docs/api/deprecations.json:
 *
 *   { schema, source, matching, entries: [ { name, kind, of?, pattern?,
 *     status: deprecated | removed | moved, replacement, movedTo?, since, note? } ] }
 *
 * The linter is offline and has no dependency, so the file is COPIED, byte for
 * byte, to data/deprecations.json, and where it came from is recorded beside
 * it in data/deprecations.source.json ({ repository, path, commit, sha256 }).
 * lib/check.mjs is imported where there is no file system, so the copy is
 * mirrored into a module as well, lib/abap2ui5-deprecations.mjs - the same
 * pair data/abap2ui5-since.json and lib/abap2ui5-since.mjs are. npm test
 * recomputes the hash and regenerates the module: a hand edit of either fails.
 *
 *   node scripts/sync-deprecations.mjs                   fetch docs main from GitHub
 *   node scripts/sync-deprecations.mjs --local <dir>     read an abap2UI5/docs checkout (its
 *                                                       HEAD; the file must be committed there)
 *   node scripts/sync-deprecations.mjs --check [...]     compare only, write nothing
 *   node scripts/sync-deprecations.mjs --module          the module from the committed copy
 *
 * Exit codes: 0 written / in sync, 1 drift (--check) or a refused local copy,
 * 2 sources unreachable or not the shape this linter reads.
 */
import fs from 'fs';
import path from 'path';
import crypto from 'crypto';
import { execFileSync } from 'child_process';
import { fileURLToPath } from 'url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
export const REPOSITORY = 'abap2UI5/docs';
export const DATA_PATH = 'docs/public/api/deprecations.json';
export const VENDORED = path.join(ROOT, 'data', 'deprecations.json');
export const SOURCE_RECORD = path.join(ROOT, 'data', 'deprecations.source.json');
export const MODULE = path.join(ROOT, 'lib', 'abap2ui5-deprecations.mjs');
export const SCHEMA = 1;
export const STATUSES = Object.freeze(['deprecated', 'removed', 'moved']);

export const sha256 = (buf) => crypto.createHash('sha256').update(buf).digest('hex');

/** Why a document is not the file this linter reads, or null. */
export function shapeProblem(doc) {
  if (!doc || typeof doc !== 'object') return 'not an object';
  if (doc.schema !== SCHEMA) return `schema ${JSON.stringify(doc.schema)}, this linter reads ${SCHEMA}`;
  if (!Array.isArray(doc.entries) || !doc.entries.length) return 'no entries';
  for (const [i, e] of doc.entries.entries()) {
    const at = `entry ${i} (${e?.name ?? '?'})`;
    if (typeof e?.name !== 'string' || !e.name || e.name !== e.name.toLowerCase()) return `${at}: the name must be a lower-case string`;
    if (typeof e.kind !== 'string' || !e.kind) return `${at}: no kind`;
    if (!STATUSES.includes(e.status)) return `${at}: status ${JSON.stringify(e.status)}`;
    if (typeof e.replacement !== 'string') return `${at}: replacement must be a string (it may be empty)`;
    if (!/^\d+\.\d+\.\d+$/.test(e.since ?? '')) return `${at}: since ${JSON.stringify(e.since)} is no release`;
    if ((e.status === 'moved') !== (typeof e.movedTo === 'string')) return `${at}: movedTo goes with status moved, and only with it`;
    if (e.movedTo !== undefined && !/^[\w.-]+\/[\w.-]+$/.test(e.movedTo)) return `${at}: movedTo ${JSON.stringify(e.movedTo)} is no owner/repository`;
    if (e.name.includes('*') !== (e.pattern === true)) return `${at}: a * in the name goes with "pattern": true, and only with it`;
  }
  return null;
}

/** The module text for the vendored document - what npm test compares. */
export function moduleText(doc) {
  return `/*
 * GENERATED by scripts/sync-deprecations.mjs from data/deprecations.json - do
 * not edit. What abap2UI5 deprecated, removed or moved to another repository,
 * as abap2UI5/docs publishes it (resources/deprecations.md, as data); read
 * through lib/deprecations.mjs.
 */
export const ABAP2UI5_DEPRECATIONS = Object.freeze(${JSON.stringify(doc, null, 2)});
`;
}

const TIMEOUT_MS = 20000;
async function fetchRetrying(url, init = {}) {
  let last;
  for (let attempt = 0; attempt < 3; attempt++) {
    try {
      const res = await fetch(url, { ...init, signal: AbortSignal.timeout(TIMEOUT_MS) });
      if (res.ok) return res;
      last = new Error(`${url}: HTTP ${res.status}`);
      if (res.status === 404) break;
    } catch (e) { last = e; }
  }
  throw last;
}

/** The file as upstream has it: `{ bytes, commit }`. */
async function readUpstream(local) {
  if (local) {
    const git = (...args) => execFileSync('git', ['-C', local, ...args], { encoding: 'utf8' }).trim();
    const commit = git('rev-parse', 'HEAD');
    // a copy of an uncommitted file would record a commit that does not hold it
    try { git('diff', '--quiet', 'HEAD', '--', DATA_PATH); } catch {
      const e = new Error(`${DATA_PATH} has uncommitted changes in ${local} - commit them first, the record has to name a commit that holds the copied bytes`);
      e.refused = true;
      throw e;
    }
    return { bytes: fs.readFileSync(path.join(local, DATA_PATH)), commit };
  }
  const headers = { accept: 'application/vnd.github+json', 'user-agent': 'abap2ui5-linter-sync' };
  if (process.env.GITHUB_TOKEN) headers.authorization = `Bearer ${process.env.GITHUB_TOKEN}`;
  const head = await (await fetchRetrying(`https://api.github.com/repos/${REPOSITORY}/commits/main`, { headers })).json();
  const commit = head.sha;
  const raw = await fetchRetrying(`https://api.github.com/repos/${REPOSITORY}/contents/${DATA_PATH}?ref=${commit}`, {
    headers: { ...headers, accept: 'application/vnd.github.raw' },
  });
  return { bytes: Buffer.from(await raw.arrayBuffer()), commit };
}

const invokedDirectly = process.argv[1] && fs.realpathSync(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) {
  const args = process.argv.slice(2);
  if (args.includes('--module')) {
    fs.writeFileSync(MODULE, moduleText(JSON.parse(fs.readFileSync(VENDORED, 'utf8'))));
    console.log(`wrote ${path.relative(process.cwd(), MODULE)}`);
    process.exit(0);
  }
  const localAt = args.indexOf('--local');
  const local = localAt !== -1 ? args[localAt + 1] : null;
  const check = args.includes('--check');
  if (localAt !== -1 && !local) {
    console.error('sync-deprecations: --local needs the path of an abap2UI5/docs checkout');
    process.exit(2);
  }
  let upstream;
  try {
    upstream = await readUpstream(local);
  } catch (e) {
    console.error(`sync-deprecations: ${e.message}`);
    process.exit(e.refused ? 1 : 2);
  }
  let doc;
  try { doc = JSON.parse(upstream.bytes.toString('utf8')); } catch (e) {
    console.error(`sync-deprecations: upstream ${DATA_PATH} is not JSON (${e.message})`);
    process.exit(2);
  }
  const problem = shapeProblem(doc);
  if (problem) {
    console.error(`sync-deprecations: upstream ${DATA_PATH} is not the shape this linter reads - ${problem}`);
    process.exit(2);
  }
  const hash = sha256(upstream.bytes);
  const record = fs.existsSync(SOURCE_RECORD) ? JSON.parse(fs.readFileSync(SOURCE_RECORD, 'utf8')) : { commit: '(none)', sha256: null };
  if (check) {
    if (record.sha256 === hash) {
      console.log(`deprecations in sync with ${REPOSITORY}@${upstream.commit.slice(0, 7)} (vendored from ${record.commit.slice(0, 7)})`);
      process.exit(0);
    }
    console.log(`deprecations drifted: ${REPOSITORY}@${upstream.commit.slice(0, 7)} ${DATA_PATH} is not the copy vendored from ${record.commit.slice(0, 7)} - run npm run sync-deprecations and review what removed-api and non-released-api now report`);
    process.exit(1);
  }
  fs.writeFileSync(VENDORED, upstream.bytes);
  fs.writeFileSync(SOURCE_RECORD, `${JSON.stringify({
    note: `Verbatim copy of ${REPOSITORY} ${DATA_PATH}, read at the commit below - what abap2UI5 deprecated, removed or moved out, generated there from resources/deprecations.md. Refresh with npm run sync-deprecations (scripts/sync-deprecations.mjs); never hand-edit data/deprecations.json or lib/abap2ui5-deprecations.mjs, npm test recomputes the hash and the module.`,
    repository: REPOSITORY,
    path: DATA_PATH,
    commit: upstream.commit,
    sha256: hash,
  }, null, 2)}\n`);
  fs.writeFileSync(MODULE, moduleText(doc));
  console.log(`${record.sha256 === hash ? 'unchanged' : 'updated'}: data/deprecations.json and lib/abap2ui5-deprecations.mjs from ${REPOSITORY}@${upstream.commit.slice(0, 7)} (${doc.entries.length} entries)`);
}
