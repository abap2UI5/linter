#!/usr/bin/env node
/*
 * generate-rule-map — docs/agents/rule-map.md: every rule, and the file it
 * is defined in.
 *
 * AGENTS.md used to carry this as a hand-written table, one row per module
 * with the rule ids it emits listed in a cell - a cell that had grown to
 * several thousand characters, was the largest part of a file every agent
 * reads before every change, and needed three assertions in the suite to
 * stay true (every id listed, in the right row, no ghosts). A table that can
 * be derived should be: the registry knows the ids, severities and
 * categories, FIXABLE and OPT_IN know theirs, and where a rule is defined is
 * where its finding is built (`emitSites( )`, the scan the rule page's
 * "Defined in" link already uses) - or, for a rule written as one unit, its
 * own file.
 *
 * No line numbers: the page links to a line and is regenerated when one
 * moves, but a map that changed with every edit of a module would be noise
 * in every pull request.
 *
 *   node scripts/generate-rule-map.mjs           write docs/agents/rule-map.md
 *   node scripts/generate-rule-map.mjs --check   exit 1 if it is stale
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { RULES, RENDER_RULE, OPT_IN, defaultSeverityOf } from '../lib/findings.mjs';
import { RULE_DOCS } from '../lib/rule-docs.mjs';
import { FIXABLE } from '../lib/fix.mjs';
import { unitRule } from '../lib/rules/index.mjs';
import { emitSites } from './generate-rules-page.mjs';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
export const RULE_MAP_FILE = path.join(ROOT, 'docs', 'agents', 'rule-map.md');

export function buildRuleMap() {
  const sites = emitSites();
  const rows = RULES.map((id) => ({
    id,
    severity: defaultSeverityOf(id),
    category: RULE_DOCS[id]?.category ?? '',
    fix: FIXABLE.includes(id),
    optIn: OPT_IN.has(id),
    unit: Boolean(unitRule(id)),
    file: `lib/${sites.get(id)?.file ?? 'findings.mjs'}`,
  }));
  const count = (pred) => rows.filter(pred).length;
  const out = [
    '# Rule map',
    '',
    '<!-- generated by scripts/generate-rule-map.mjs — do not edit; npm test fails while it is stale -->',
    '',
    `${rows.length} rules: ${count((r) => r.severity === 'error')} errors, ${count((r) => r.severity === 'warning')} warnings, `
      + `${count((r) => r.severity === 'hint')} hints · ${count((r) => r.fix)} can carry a fix · ${count((r) => r.optIn)} opt-in · `
      + `${count((r) => r.unit)} written as one unit (\`lib/rules/\`, see AGENTS.md).`,
    '',
    `\`${RENDER_RULE}\` is not in the registry: it labels a render-gate failure (\`lib/render.mjs\`) and is configurable only through \`rules['${RENDER_RULE}']\`.`,
    '',
    'What each rule means is its card — `abap2ui5lint --explain <id>`, or the rule reference generated from the same prose (`site/index.html`).',
    '',
    '## By module',
    '',
    'Where the finding is built. Grep the id in that file for the exact line.',
    '',
  ];
  const byFile = new Map();
  for (const r of rows) (byFile.get(r.file) ?? byFile.set(r.file, []).get(r.file)).push(r);
  const unitFiles = [...byFile.keys()].filter((f) => f.startsWith('lib/rules/'));
  for (const file of [...byFile.keys()].filter((f) => !f.startsWith('lib/rules/')).sort((a, b) => byFile.get(b).length - byFile.get(a).length || a.localeCompare(b))) {
    out.push(`- \`${file}\` (${byFile.get(file).length}): ${byFile.get(file).map((r) => `\`${r.id}\``).join(', ')}`);
  }
  if (unitFiles.length) out.push(`- \`lib/rules/<id>.mjs\` (${unitFiles.length}, one file each): ${unitFiles.sort().map((f) => `\`${byFile.get(f)[0].id}\``).join(', ')}`);
  out.push('', '## All rules', '', '| Rule | Severity | Category | Fix | Opt-in | Defined in |', '| --- | --- | --- | --- | --- | --- |');
  for (const r of rows) {
    out.push(`| \`${r.id}\` | ${r.severity} | ${r.category} | ${r.fix ? 'yes' : ''} | ${r.optIn ? 'yes' : ''} | \`${r.file}\` |`);
  }
  return `${out.join('\n')}\n`;
}

const invokedDirectly = process.argv[1] && fs.realpathSync(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) {
  const text = buildRuleMap();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(RULE_MAP_FILE) ? fs.readFileSync(RULE_MAP_FILE, 'utf8') : '';
    if (current !== text) {
      console.error('docs/agents/rule-map.md is stale - run: npm run generate-rule-map');
      process.exit(1);
    }
    console.log('docs/agents/rule-map.md is in sync');
  } else {
    fs.mkdirSync(path.dirname(RULE_MAP_FILE), { recursive: true });
    fs.writeFileSync(RULE_MAP_FILE, text);
    console.log(`wrote docs/agents/rule-map.md (${RULES.length} rules)`);
  }
}
