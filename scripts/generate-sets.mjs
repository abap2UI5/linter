#!/usr/bin/env node
/*
 * generate-sets — lib/abap2ui5-sets.mjs: the mirrored sets that are nothing
 * but their set, as a module.
 *
 * Most of what lib/frontend-actions.mjs and lib/formatters.mjs mirror from
 * abap2UI5 is a plain list - the curated formatters, the CSS properties, the
 * denied control methods, the filter operators - and each was typed in here
 * by hand and compared with upstream afterwards. With abap2UI5 writing those
 * lists down itself (data/abap2ui5-manifest.json, see
 * scripts/sync-manifest.mjs) the typing is the part left over: this script
 * turns the manifest's lists into a module, and the mirrors take their
 * values from it. An upstream change to one of them is `npm run
 * sync-manifest` and nothing else.
 *
 * A MODULE rather than a read of the JSON file, because lib/check.mjs is
 * imported by hosts that have no file system (a browser bundle): what a rule
 * judges against has to arrive with the code.
 *
 * Only the keys in KEYS are generated - the mirrors that add nothing to
 * their list. The others carry knowledge the manifest does not hold (the
 * release a global target needs, the slot order a message prints, the
 * replacement an obsolete control names) and stay written by hand, held to
 * the manifest by `check-upstream --manifest` in the suite.
 *
 *   node scripts/generate-sets.mjs           write lib/abap2ui5-sets.mjs
 *   node scripts/generate-sets.mjs --check   exit 1 if it is stale
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const MANIFEST = path.join(ROOT, 'data', 'abap2ui5-manifest.json');
export const SETS_FILE = path.join(ROOT, 'lib', 'abap2ui5-sets.mjs');

export const KEYS = Object.freeze([
  'formatters', 'clipboardCallbacks', 'messageBoxTypes', 'cssProperties',
  'controlMethodDenyExact', 'controlMethodDenyPrefixes', 'bindingMethods', 'filterOperators',
  'shortcutModifiers', 'shortcutAliases', 'urlHelperActions', 'urlPolicies', 'controlMethodKinds',
]);

export function buildSets(manifestText = fs.readFileSync(MANIFEST, 'utf8')) {
  /* Parsed here, not through check-upstream's readManifest( ): that script
   * imports the mirrors, the mirrors import the file this one writes, and a
   * generator that needs its own output to start cannot repair it. */
  const manifest = JSON.parse(String(manifestText).replace(/^\uFEFF/, ''));
  for (const key of KEYS) {
    if (typeof manifest[key] !== 'object' || manifest[key] === null) throw new Error(`data/abap2ui5-manifest.json has no '${key}'`);
  }
  const body = KEYS.map((key) => `  ${key}: ${JSON.stringify(manifest[key], null, 2).replace(/\n/g, '\n  ')},`).join('\n');
  return `/*
 * GENERATED by scripts/generate-sets.mjs from data/abap2ui5-manifest.json -
 * do not edit. The closed sets of abap2UI5 that the linter takes as they
 * are: refresh the manifest (npm run sync-manifest) and this file follows.
 * What each one is for is said where it is used - lib/frontend-actions.mjs
 * and lib/formatters.mjs.
 */
export const UPSTREAM_SETS = Object.freeze({
${body}
});
`;
}

const invokedDirectly = process.argv[1] && fs.realpathSync(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) {
  const text = buildSets();
  if (process.argv.includes('--check')) {
    if ((fs.existsSync(SETS_FILE) ? fs.readFileSync(SETS_FILE, 'utf8') : '') !== text) {
      console.error('lib/abap2ui5-sets.mjs is stale - run: npm run generate-sets');
      process.exit(1);
    }
    console.log('lib/abap2ui5-sets.mjs is in sync');
  } else {
    fs.writeFileSync(SETS_FILE, text);
    console.log('wrote lib/abap2ui5-sets.mjs');
  }
}
