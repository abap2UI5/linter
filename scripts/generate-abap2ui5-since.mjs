#!/usr/bin/env node
/*
 * Builds data/abap2ui5-since.json - the abap2UI5 release each name of the
 * client API first shipped in.
 *
 * The linter's mirrors of abap2UI5 (data/abap2ui5-manifest.json and the
 * lists in lib/) are what abap2UI5's `main` holds TODAY. A consumer is not on
 * main: an app on an installation of 1.140.0 that writes
 * `client->cs_event-offline_queue` (added later) passes every rule and does
 * not compile on its system. This file is what lets the gate answer that,
 * given the release the consumer runs (`abap2ui5` in abap2ui5lint.jsonc, or
 * --abap2ui5): rule `abap2ui5-api-too-new`.
 *
 * Source: `src/02/z2ui5_if_client.intf.abap` at every release tag of
 * abap2UI5/abap2UI5 from FIRST up - the components of `cs_event` and the
 * METHODS of the interface. A name's `since` is the first tag that has it; a
 * name already in FIRST is not recorded at all (it means "at or before
 * FIRST", and the rule is silent for it); a name only `main` has so far is
 * recorded as "main". Tags whose file is not at that path
 * end the scan downwards: the interface lived elsewhere before FIRST.
 *
 * Needs network (raw.githubusercontent.com and the tag list over git), so it
 * is not part of `npm test`: the committed file is the contract, and the
 * suite checks its shape.
 *
 * The data file is mirrored into lib/abap2ui5-since.mjs, the way
 * lib/abap2ui5-sets.mjs mirrors the manifest: a browser bundle (the VS Code
 * extension's web build) cannot read a file, and lib/check.mjs reaches the
 * rule. `--module` rewrites the module from the committed data file alone
 * (no network); npm test fails while the two differ.
 *
 *   node scripts/generate-abap2ui5-since.mjs            # data file + module
 *   node scripts/generate-abap2ui5-since.mjs --module   # the module from the data file
 *   node scripts/generate-abap2ui5-since.mjs --check    # compare only
 */
import fs from 'fs';
import path from 'path';
import { execFileSync } from 'child_process';
import { fileURLToPath } from 'url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'data', 'abap2ui5-since.json');
const MODULE = path.join(ROOT, 'lib', 'abap2ui5-since.mjs');
const REPO = 'abap2UI5/abap2UI5';
const FILE = 'src/02/z2ui5_if_client.intf.abap';
const FIRST = '1.120.0';

const cmp = (a, b) => {
  const x = a.split('.').map(Number); const y = b.split('.').map(Number);
  for (let i = 0; i < 3; i++) if ((x[i] ?? 0) !== (y[i] ?? 0)) return (x[i] ?? 0) - (y[i] ?? 0);
  return 0;
};

/* Release tags are `1.148.0`; the `-702` twins are the downport of the same
 * release and carry the same API. */
const tags = execFileSync('git', ['ls-remote', '--tags', `https://github.com/${REPO}`], { encoding: 'utf8' })
  .split('\n').map((l) => l.split('refs/tags/')[1]).filter((t) => t && /^\d+\.\d+\.\d+$/.test(t))
  .filter((t) => cmp(t, FIRST) >= 0).sort(cmp);

/* The components of `cs_event` (upper case, as the frontend names them) and
 * the METHODS of the interface (lower case, as a call writes them). Comments
 * are dropped first: the interface's ABAP Doc quotes old names. */
export function readApi(src) {
  const code = src.split('\n').map((l) => (l.trimStart().startsWith('*') ? '' : l.replace(/".*$/, ''))).join('\n');
  const events = new Set();
  const block = code.match(/BEGIN OF cs_event\s*,([\s\S]*?)END OF cs_event/i);
  for (const m of block?.[1].matchAll(/^\s*(\w+)\s+TYPE\b/gim) ?? []) events.add(m[1].toUpperCase());
  const methods = new Set();
  for (const m of code.matchAll(/^\s*METHODS\s+(\w+)/gim)) methods.add(m[1].toLowerCase());
  return { events, methods };
}

/** The module text for a data object - what npm test compares. */
export function moduleText(data) {
  return `/*
 * GENERATED by scripts/generate-abap2ui5-since.mjs from data/abap2ui5-since.json -
 * do not edit. The abap2UI5 release each name of the client API first
 * shipped in (rule abap2ui5-api-too-new); a name absent here is at or before
 * ${data.first}.
 */
export const ABAP2UI5_SINCE = Object.freeze(${JSON.stringify(data, null, 2)});
`;
}

async function main() {
  if (process.argv.includes('--module')) {
    fs.writeFileSync(MODULE, moduleText(JSON.parse(fs.readFileSync(OUT, 'utf8'))));
    console.error(`wrote ${path.relative(process.cwd(), MODULE)}`);
    return;
  }
  const since = { clientEvents: {}, clientMethods: {} };
  let first = null;
  let latest = null;
  for (const tag of tags) {
    const res = await fetch(`https://raw.githubusercontent.com/${REPO}/${tag}/${FILE}`);
    if (!res.ok) { console.error(`${tag}: ${res.status} - skipped`); continue; }
    const { events, methods } = readApi(await res.text());
    if (!first) {
      first = tag;
      for (const e of events) since.clientEvents[e] = null;
      for (const m of methods) since.clientMethods[m] = null;
    } else {
      for (const e of events) if (!(e in since.clientEvents)) since.clientEvents[e] = tag;
      for (const m of methods) if (!(m in since.clientMethods)) since.clientMethods[m] = tag;
    }
    latest = tag;
    console.error(`${tag}: ${events.size} events, ${methods.size} methods`);
  }
  if (!first) throw new Error('no release tag could be read - network?');
  /* main after the last release: a name there is in no release yet, and an
   * app written against main does not activate on ANY installed release -
   * recorded as "main", newer than every release */
  {
    const res = await fetch(`https://raw.githubusercontent.com/${REPO}/main/${FILE}`);
    if (res.ok) {
      const { events, methods } = readApi(await res.text());
      for (const e of events) if (!(e in since.clientEvents)) since.clientEvents[e] = 'main';
      for (const m of methods) if (!(m in since.clientMethods)) since.clientMethods[m] = 'main';
    }
  }
  const strip = (o) => Object.fromEntries(Object.entries(o).filter(([, v]) => v).sort(([a], [b]) => a.localeCompare(b)));
  const data = {
    schema: 1,
    source: `${REPO} ${FILE}, release tags ${first} to ${latest}`,
    first,
    latest,
    clientEvents: strip(since.clientEvents),
    clientMethods: strip(since.clientMethods),
  };
  const text = `${JSON.stringify(data, null, 2)}\n`;
  if (process.argv.includes('--check')) {
    const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (now !== text) { console.error('data/abap2ui5-since.json is stale - node scripts/generate-abap2ui5-since.mjs'); process.exit(1); }
    console.error('data/abap2ui5-since.json is current');
    return;
  }
  fs.writeFileSync(OUT, text);
  fs.writeFileSync(MODULE, moduleText(data));
  console.error(`wrote ${path.relative(process.cwd(), OUT)} and ${path.relative(process.cwd(), MODULE)}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) await main();
